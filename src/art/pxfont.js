const G = new Map();
function parse(s) { let top = 0; if (s[0] === '+') { top = -2; s = s.slice(1); } const rows = s.split('/'); return { rows, top, w: Math.max(1, ...rows.map(r => r.length)) }; }
function glyph(ch) {
  let g = G.get(ch); if (g) return g;
  let s = LAT[ch] ?? CYR[ch];
  if (s && s.length === 1) s = LAT[s] ?? CYR[s];   // ссылка на латинскую букву того же вида
  g = ch === ' ' || ch === '\n' ? { rows: [], top: 0, w: 3 } : parse(s ?? LAT['?']);
  G.set(ch, g); return g;
}
const norm = s => String(s).replace(/№/g, 'No').replace(/\t/g, ' ');
// ширина строки в пикселях глифа (шаг = ширина + 1)
export function glyphWidth(s) { let w = 0; for (const ch of norm(s)) w += glyph(ch).w + 1; return Math.max(0, w - 1); }

// размер «пикселя шрифта» в логических единицах по кеглю живописной версии — ступенями, чтобы соседние кегли
// (16 и 17, 28 и 30) не расходились по размеру
export const glyphUnit = (size = 18) => size < 16 ? 1 : size < 22 ? 1.5 : size < 30 ? 2 : size < 40 ? 3 : size < 56 ? 4 : 5;
export const PXL = { on: false, main: null, low: null, n: 2, S: 1, q: [], raw: {}, bx0: 1e9, by0: 1e9, bx1: -1e9, by1: -1e9 };
// целый пиксель шрифта в пикселях экрана
const devUnit = (size, zoom = 1) => Math.max(1, Math.floor(glyphUnit(size) * zoom * PXL.S + 0.01));
// ширина в логических единицах (для переноса строк) — совпадает с тем, что будет нарисовано
export function pxMeasure(s, size) { return glyphWidth(s) * devUnit(size) / PXL.S; }
export const pxLineH = size => 13 * devUnit(size) / PXL.S;

// строка → холст (кэш): обводка 3×3 вокруг каждого пикселя, затем сам цвет
const cache = new Map();
function render(s, u, col, oc) {
  const key = s + '\u0001' + u + col + oc; let c = cache.get(key);
  if (c) { cache.delete(key); cache.set(key, c); return c; }
  const w = glyphWidth(s); c = document.createElement('canvas'); c.width = (w + 2) * u; c.height = 15 * u; const x = c.getContext('2d');
  const cells = []; let cx = 1;
  for (const ch of norm(s)) { const g = glyph(ch); g.rows.forEach((r, j) => { for (let i = 0; i < r.length; i++) if (r[i] === '#') cells.push(cx + i, j + g.top + 3); }); cx += g.w + 1; }
  if (oc) { x.fillStyle = oc; for (let k = 0; k < cells.length; k += 2) x.fillRect((cells[k] - 1) * u, (cells[k + 1] - 1) * u, 3 * u, 3 * u); }
  x.fillStyle = col; for (let k = 0; k < cells.length; k += 2) x.fillRect(cells[k] * u, cells[k + 1] * u, u, u);
  c.tw = w; cache.set(key, c); if (cache.size > 600) cache.delete(cache.keys().next().value);
  return c;
}
// смещение верха холста от точки привязки (в пикселях шрифта): верх прописной — 3-я строка холста, линия букв — 12-я
const VOFF = { middle: 7.5, top: 2, hanging: 2, bottom: 12, alphabetic: 12, ideographic: 12 };
const shiftX = (align, tw, u) => align === 'center' ? tw * u / 2 : (align === 'right' || align === 'end') ? tw * u : 0;

// текст пиксельным шрифтом: o как у text() (size, align, base, color, shadow, stroke, strokeColor)
export function pxText(ctx, s, x, y, o = {}) {
  s = norm(s); if (!s.trim()) return;
  const col = o.color || '#ead9c6', oc = (o.shadow === false && !o.stroke) ? null : (o.strokeColor || '#101820');
  const align = o.align || 'center', base = o.base || 'middle';
  if (PXL.on && ctx === PXL.low) {
    const a = ctx.globalAlpha; if (a <= 0.01) return;
    const m = ctx.getTransform(), zoom = Math.hypot(m.a, m.b) * 2, u = devUnit(o.size, zoom), c = render(s, u, col, oc);
    const n = PXL.n, dx = (m.a * x + m.c * y + m.e) * n, dy = (m.b * x + m.d * y + m.f) * n;
    const left = Math.round(dx - shiftX(align, c.tw, u)) - u, top = Math.round(dy - (VOFF[base] ?? 7.5) * u);
    const b = [left / n, top / n, (left + c.width) / n, (top + c.height) / n];
    PXL.q.push({ c, x: left, y: top, a, b });
    PXL.bx0 = Math.min(PXL.bx0, b[0]); PXL.by0 = Math.min(PXL.by0, b[1]); PXL.bx1 = Math.max(PXL.bx1, b[2]); PXL.by1 = Math.max(PXL.by1, b[3]);
    return;
  }
  // запасной путь: чужой холст — пиксель шрифта в его единицах
  const u = Math.max(1, Math.floor(glyphUnit(o.size))), c = render(s, u, col, oc);
  const sm = ctx.imageSmoothingEnabled; ctx.imageSmoothingEnabled = false;
  ctx.drawImage(c, Math.round(x - shiftX(align, c.tw, u)) - u, Math.round(y - (VOFF[base] ?? 7.5) * u)); ctx.imageSmoothingEnabled = sm;
}

// ---- слой: перехват рисования в низкий буфер
const DRAW = ['fillRect', 'strokeRect', 'clearRect', 'drawImage', 'fill', 'stroke', 'fillText', 'strokeText', 'putImageData'];
function overlaps(ctx, m, a) {
  if (PXL.under) return false;   // погода (дождь, туман) — всегда под текстом, не сбрасывает очередь
  let x, y, w, h;
  if (m === 'drawImage') { if (a.length === 3) { x = a[1]; y = a[2]; w = a[0].width; h = a[0].height; } else if (a.length === 5) { x = a[1]; y = a[2]; w = a[3]; h = a[4]; } else { x = a[5]; y = a[6]; w = a[7]; h = a[8]; } }
  else if (m === 'fillRect' || m === 'clearRect' || m === 'strokeRect') { [x, y, w, h] = a; if (m === 'strokeRect') { const lw = ctx.lineWidth; x -= lw; y -= lw; w += 2 * lw; h += 2 * lw; } }
  else return true;   // контуры и прочее — без границ: считаем, что задевают
  const t = ctx.getTransform(); let x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9;
  for (const [px, py] of [[x, y], [x + w, y], [x, y + h], [x + w, y + h]]) { const X = t.a * px + t.c * py + t.e, Y = t.b * px + t.d * py + t.f; if (X < x0) x0 = X; if (X > x1) x1 = X; if (Y < y0) y0 = Y; if (Y > y1) y1 = Y; }
  if (x1 <= PXL.bx0 || x0 >= PXL.bx1 || y1 <= PXL.by0 || y0 >= PXL.by1) return false;
  for (const q of PXL.q) if (!(x1 <= q.b[0] || x0 >= q.b[2] || y1 <= q.b[1] || y0 >= q.b[3])) return true;
  return false;
}
export function pxAttach(lctx) {
  for (const m of DRAW) { const f = lctx[m]; PXL.raw[m] = f; lctx[m] = function (...a) { if (PXL.q.length && overlaps(lctx, m, a)) pxFlush(); return f.apply(lctx, a); }; }
}
// растянуть буфер на экран, нарисовать текст из очереди, очистить буфер
export function pxFlush() {
  const { main, low } = PXL; if (!main) return;
  main.save(); main.setTransform(1, 0, 0, 1, 0, 0); main.globalAlpha = 1; main.globalCompositeOperation = 'source-over'; main.imageSmoothingEnabled = false;
  main.drawImage(low.canvas, 0, 0, main.canvas.width, main.canvas.height);
  for (const t of PXL.q) { main.globalAlpha = t.a; main.drawImage(t.c, t.x, t.y); }
  main.restore();
  low.save(); low.setTransform(1, 0, 0, 1, 0, 0); low.globalAlpha = 1; low.globalCompositeOperation = 'source-over'; PXL.raw.clearRect.call(low, 0, 0, low.canvas.width, low.canvas.height); low.restore();
  PXL.q.length = 0; PXL.bx0 = PXL.by0 = 1e9; PXL.bx1 = PXL.by1 = -1e9;
}
